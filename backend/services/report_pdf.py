"""
Report PDF Service

render_report_pdf(title, case_name, sections) → bytes

Lays out a simple A4 report (title, case line, headed sections) with
PyMuPDF's Story API. Section content is plain text: blank lines separate
paragraphs and lines starting with "- " become bullet lists.
"""

import html
import io
from datetime import date

import fitz  # PyMuPDF

_CSS = """
body { font-family: sans-serif; font-size: 10.5pt; line-height: 1.45; color: #1e293b; }
h1 { font-size: 18pt; color: #1F3D6E; margin-bottom: 2pt; }
p.meta { font-size: 9pt; color: #64748b; margin-top: 0; }
h2 { font-size: 12.5pt; color: #1F3D6E; margin-top: 14pt; margin-bottom: 4pt; }
li { margin-bottom: 2pt; }
p.footer { font-size: 8pt; color: #94a3b8; margin-top: 18pt; }
"""

_MARGIN = 54  # points (0.75 in)


def _content_html(text: str) -> str:
    parts: list[str] = []
    for block in text.replace("\r\n", "\n").split("\n\n"):
        lines = [ln.strip() for ln in block.split("\n") if ln.strip()]
        if not lines:
            continue
        if all(ln.startswith(("- ", "* ")) for ln in lines):
            items = "".join(f"<li>{html.escape(ln[2:])}</li>" for ln in lines)
            parts.append(f"<ul>{items}</ul>")
        else:
            parts.append(f"<p>{'<br/>'.join(html.escape(ln) for ln in lines)}</p>")
    return "".join(parts)


def render_report_pdf(title: str, case_name: str, sections: list[dict]) -> bytes:
    body = [
        f"<h1>{html.escape(title)}</h1>",
        f"<p class='meta'>{html.escape(case_name)} · {date.today():%d %B %Y}</p>",
    ]
    for section in sections:
        if section.get("heading"):
            body.append(f"<h2>{html.escape(section['heading'])}</h2>")
        body.append(_content_html(section.get("content", "")))
    body.append("<p class='footer'>Generated by LexMind AI — AI-generated content; verify against "
                "primary sources before relying on it.</p>")

    story = fitz.Story(html="".join(body), user_css=_CSS)
    buffer = io.BytesIO()
    writer = fitz.DocumentWriter(buffer)
    page_rect = fitz.paper_rect("a4")
    content_rect = page_rect + (_MARGIN, _MARGIN, -_MARGIN, -_MARGIN)

    more = True
    while more:
        device = writer.begin_page(page_rect)
        more, _ = story.place(content_rect)
        story.draw(device)
        writer.end_page()
    writer.close()
    return buffer.getvalue()
